/**
 * The docs have four sidebars, one per tab in the tab row under the navbar
 * (see src/components/DocsTabs):
 *
 *   docsSidebar - Documentation: everything, including the pages below
 *   aiSidebar   - AI: building with AI, MCP server, agent skills, AI frameworks
 *   apiSidebar  - API Reference: REST API and webhooks
 *   sdkSidebar  - SDKs: Node.js SDK, Python SDK and CLI
 *
 * A page that is in several sidebars is shown with the LAST sidebar listed
 * here that contains it. That is why docsSidebar comes first: AI, API and SDK
 * pages open in their own tab, and every other page opens in Documentation.
 *
 * When you add a new doc at the root of /docs, add it here. Docs added inside
 * an existing folder are picked up automatically.
 *
 * @type {import('@docusaurus/plugin-content-docs').SidebarsConfig}
 */

/**
 * A category whose items are generated from a folder, using that folder's
 * _category_.json for the label and index page.
 * @param {string} dirName
 * @param {Record<string, any>} [overrides]
 */
function folderCategory(dirName, overrides = {}) {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const {position, ...meta} = require(`./docs/${dirName}/_category_.json`);
  return {
    type: 'category',
    ...meta,
    items: [{type: 'autogenerated', dirName}],
    ...overrides,
  };
}

/**
 * The same folder as a plain category, without an index page. Used in
 * docsSidebar for folders whose index page already belongs to another tab,
 * so the same /category/... page isn't generated twice.
 * @param {string} dirName
 * @param {string} label
 */
function folderGroup(dirName, label) {
  return {type: 'category', label, items: [{type: 'autogenerated', dirName}]};
}

